export function isRtlLanguage(lang?: string): boolean {
  return !lang || lang === 'ar' || lang === 'ur';
}

export function getLocaleStrings(lang?: string): TranslationMap {
  if (!lang || lang === 'ar') return strings.ar;
  if (lang === 'en') return strings.en;
  if (lang === 'fr') return { ...strings.en, ...frOverrides };
  if (lang === 'es') return { ...strings.en, ...esOverrides };
  if (lang === 'tr') return { ...strings.en, ...trOverrides };
  if (lang === 'ur') return { ...strings.ar, ...urOverrides };
  return strings.en;
}

